"""Finite groups with exponent-tuple (pc-normal-form) element encoding.

Every group declares an ordered generator sequence ``(g1..gk)`` with orders
``(r1..rk)`` such that ``g1^e1 * ... * gk^ek`` with ``e_i in [0, r_i)`` names
each element exactly once — the polycyclic normal form GAP uses for solvable
groups. The exponent tuple ``[e1..ek]`` is the spec-facing element encoding
(design doc: docs/01_code_family_design.md §4.3). Internally generators are
realized as permutations; bijectivity of the normal form is asserted at
construction, and the Cayley table is precomputed so regular representations
and subgroup closures never touch permutations again.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from itertools import product as _mixed_radix
from typing import Iterable, Sequence

import numpy as np

Perm = tuple[int, ...]
ExponentTuple = tuple[int, ...]


def compose(g: Perm, h: Perm) -> Perm:
    """Permutation product g∘h (apply h first, then g)."""

    return tuple(g[h[i]] for i in range(len(g)))


def invert(g: Perm) -> Perm:
    result = [0] * len(g)
    for i, gi in enumerate(g):
        result[gi] = i
    return tuple(result)


def perm_order(g: Perm) -> int:
    identity = tuple(range(len(g)))
    power, order = g, 1
    while power != identity:
        power = compose(power, g)
        order += 1
    return order


@dataclass(frozen=True)
class Group:
    """A finite group in canonical exponent-tuple presentation."""

    name: str
    kind: str
    generator_orders: tuple[int, ...]
    elements: tuple[ExponentTuple, ...]
    index: dict[ExponentTuple, int] = field(repr=False)
    cayley: np.ndarray = field(repr=False)
    inverse: np.ndarray = field(repr=False)
    gap_id: tuple[int, int] | None = None

    @property
    def order(self) -> int:
        return len(self.elements)

    @property
    def is_abelian(self) -> bool:
        return bool(np.array_equal(self.cayley, self.cayley.T))

    def normalize_tuple(self, value: Sequence[int]) -> ExponentTuple:
        """Reduce a raw exponent tuple to normal form ``e_i mod r_i``."""

        orders = self.generator_orders
        if not isinstance(value, (list, tuple)) or len(value) != len(orders):
            raise ValueError(
                f"group '{self.name}' elements are exponent {len(orders)}-tuples "
                f"[e1..e{len(orders)}] with orders {list(orders)}"
            )
        return tuple(int(entry) % order for entry, order in zip(value, orders))

    def element_index(self, value: Sequence[int]) -> int:
        return self.index[self.normalize_tuple(value)]

    def subgroup_closure(self, generator_indices: Iterable[int]) -> set[int]:
        """Indices of the subgroup generated by the given element indices."""

        closure = {0}
        frontier = [0]
        generators = sorted({int(i) for i in generator_indices})
        while frontier:
            current = frontier.pop()
            for generator in generators:
                product = int(self.cayley[current, generator])
                if product not in closure:
                    closure.add(product)
                    frontier.append(product)
        return closure

    def generates(self, indices: Iterable[int]) -> bool:
        return len(self.subgroup_closure(indices)) == self.order

    def left_regular(self, subset_indices: Iterable[int]) -> np.ndarray:
        """L(sum_g g) over the subset: L(g)[g*h, h] = 1."""

        matrix = np.zeros((self.order, self.order), dtype=np.uint8)
        for member in subset_indices:
            matrix[self.cayley[int(member), :], np.arange(self.order)] ^= 1
        return matrix

    def right_regular(self, subset_indices: Iterable[int]) -> np.ndarray:
        """R(sum_g g) over the subset: R(g)[h*g, h] = 1."""

        matrix = np.zeros((self.order, self.order), dtype=np.uint8)
        for member in subset_indices:
            matrix[self.cayley[:, int(member)], np.arange(self.order)] ^= 1
        return matrix


def group_from_generators(
    *,
    name: str,
    kind: str,
    generator_perms: Sequence[Perm],
    generator_orders: Sequence[int],
    gap_id: tuple[int, int] | None = None,
) -> Group:
    """Build a Group and assert the generator sequence gives a normal form."""

    orders = tuple(int(order) for order in generator_orders)
    powers: list[list[Perm]] = []
    for perm, order in zip(generator_perms, orders):
        if perm_order(perm) != order:
            raise ValueError(f"{name}: declared generator order {order} is wrong")
        chain = [tuple(range(len(perm)))]
        for _ in range(order - 1):
            chain.append(compose(chain[-1], perm))
        powers.append(chain)

    elements: list[ExponentTuple] = []
    perms: list[Perm] = []
    for exponents in _mixed_radix(*(range(order) for order in orders)):
        perm = tuple(range(len(generator_perms[0])))
        for generator_index, exponent in enumerate(exponents):
            perm = compose(perm, powers[generator_index][exponent])
        elements.append(tuple(exponents))
        perms.append(perm)
    if len(set(perms)) != len(perms):
        raise ValueError(f"{name}: generator sequence does not yield a normal form")

    perm_index = {perm: position for position, perm in enumerate(perms)}
    size = len(perms)
    cayley = np.zeros((size, size), dtype=np.int32)
    inverse = np.zeros(size, dtype=np.int32)
    for i, left in enumerate(perms):
        inverse[i] = perm_index[invert(left)]
        for j, right in enumerate(perms):
            cayley[i, j] = perm_index[compose(left, right)]

    return Group(
        name=name,
        kind=kind,
        generator_orders=orders,
        elements=tuple(elements),
        index={element: position for position, element in enumerate(elements)},
        cayley=cayley,
        inverse=inverse,
        gap_id=gap_id,
    )


def cycle_perm(length: int) -> Perm:
    return tuple((i + 1) % length for i in range(length))


def pad_perm(perm: Perm, *, offset: int, total: int) -> Perm:
    """Embed a permutation of a block into identity on ``total`` points."""

    result = list(range(total))
    for i, target in enumerate(perm):
        result[offset + i] = offset + target
    return tuple(result)

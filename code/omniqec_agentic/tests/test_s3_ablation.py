def test_no_slow_orchestrator_context_carries_the_ablation_notice_only_then(tmp_path: Path) -> None:
    from omniqec_agentic.orchestrator.loop import NO_SLOW_NOTICE, AgenticPolicy
    from omniqec_agentic.orchestrator.manual import render_dynamic, render_static
    from omniqec_agentic.tools.context import ToolContext

    for mode, expected in (("no_slow", True), ("full", False)):
        state = campaign_state(tmp_path / mode)
        state["protocol"]["ablation"] = mode
        manual_dir = tmp_path / mode / "manual"
        ctx = ToolContext(run_dir=tmp_path / mode, manual_dir=manual_dir, state=dict(state), turn=5)

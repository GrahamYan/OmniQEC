def _audit_state(run_dir: Path, *, ablation: str, policy: str) -> tuple[dict, dict, SimpleNamespace]:
    turn_dir = run_dir / "turns" / "turn_0003"
    gen_dir = turn_dir / "cycle" / "fast" / "generations" / "g0001"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (turn_dir / "cycle").mkdir(exist_ok=True)
    (turn_dir / "cycle" / "agentic_cycle_summary.json").write_text("{}", encoding="utf-8")
    (turn_dir / "cycle" / "fast" / "funsearch_summary.json").write_text("{}", encoding="utf-8")
    (gen_dir / "llm_raw.jsonl").write_text(
        json.dumps({"status": "ok", "engine_info": {"provider": "openai", "model": "claude-opus-5"}}) + "\n",
        encoding="utf-8",
    )
    protocol = {"strict_turns": True, "required_provider": "openai", "required_model": "claude-opus-5",
                "proposal_count": 2, "generations_per_turn": 1, "rng_seeds_per_program": 1}
    if ablation != "full":
        protocol["ablation"] = ablation
    state = {"run_dir": str(run_dir), "turn": 3, "protocol": protocol}
    plan = {"policy": policy, "provider": "openai", "proposal_count": 2, "generations": 1, "rng_seeds_per_program": 1}
    summary = SimpleNamespace(to_dict=lambda: {
        "provider": "openai", "proposal_count": 2, "generations": 1, "status": "ok", "slow_summary": None,
        "funsearch_summary": {"provider": "openai", "proposal_count_requested_total": 2,
                              "proposal_count_missing_total": 0, "status_counts": {"ok": 1},
                              "rng_seeds_per_program": 1,
                              "artifact_paths": {"summary": str(turn_dir / "cycle" / "fast" / "funsearch_summary.json"),
                                                 "generations": str(turn_dir / "cycle" / "fast" / "generations")}},
    })
    return state, plan, summary


def test_strict_audit_accepts_the_no_feedback_policy_without_orchestrator_calls(tmp_path: Path) -> None:
    from omniqec_agentic.workflow.graph import _audit_turn_execution

    state, plan, summary = _audit_state(tmp_path, ablation="no_feedback", policy="ablation_no_feedback_v1")
    audit = _audit_turn_execution(state, plan, summary)
    assert audit["status"] == "execution_complete" and audit["checks"]["ablation"] == "no_feedback"

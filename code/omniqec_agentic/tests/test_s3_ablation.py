    with pytest.raises(RuntimeError, match="plan policy"):
        _audit_turn_execution(state, plan, summary)
    for mode in ("full", "no_slow"):
        state, plan, summary = _audit_state(tmp_path / mode, ablation=mode, policy="ablation_no_feedback_v1")
        with pytest.raises(RuntimeError, match="plan policy"):
            _audit_turn_execution(state, plan, summary)



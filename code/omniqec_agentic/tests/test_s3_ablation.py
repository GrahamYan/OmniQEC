@pytest.mark.parametrize("task", ["memory", "cnot_dense"])
def test_protocol_snapshot_matches_golden_and_only_gains_the_ablation_key(task: str) -> None:
    expected = json.loads((GOLDEN / f"snapshot_{task}.json").read_text(encoding="utf-8"))
    assert json.loads(json.dumps(snapshot_dict(task))) == expected
    assert json.loads(json.dumps(snapshot_dict(task, ablation="full"))) == expected
    for mode in ("no_slow", "no_feedback"):
        got = json.loads(json.dumps(snapshot_dict(task, ablation=mode, feedback_mode=ABLATION_FEEDBACK_MODE[mode])))
        assert got.pop("ablation") == mode
        assert got.pop("feedback_mode") == ABLATION_FEEDBACK_MODE[mode]
        base = dict(expected)
        base.pop("feedback_mode")
        assert got == base
    with pytest.raises(ValueError, match="requires feedback_mode"):
        snapshot_dict(task, ablation="no_slow", feedback_mode="both")
    with pytest.raises(ValueError, match="unknown ablation"):
        snapshot_dict(task, ablation="no_llm", feedback_mode="none")



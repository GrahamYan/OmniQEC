def _execute_plan_capture(monkeypatch, run_dir: Path, *, ablation: str, task: str = "cnot_dense") -> dict:
    import omniqec_agentic.campaign as campaign
    import omniqec_agentic.workflow.graph as graph
    from omniqec_agentic.config import RacingConfig

    (run_dir / "evidence_rows.jsonl").write_text(
        json.dumps({"code_hash": "aa" * 12, "program_id": "g0003_p0002", "per_logical_per_round": 1.4e-4,
                    "k": 2, "d_search": 7, "family": "bb", "n": 72, "max_check_weight": 4}) + "\n",
        encoding="utf-8",
    )
    (run_dir / "structural_ledger.jsonl").write_text(
        json.dumps({"code_hash": "aa" * 12, "canonical_hash": "CANON_A", "max_check_weight": 4}) + "\n",
        encoding="utf-8",
    )
    slow_ptr = run_dir / "slow_overlay.json"
    slow_ptr.write_text(json.dumps({"slow_feedback": {"best_results": [], "proposal_guidance": ["measured"]}}), encoding="utf-8")
    comp_dir = run_dir / "turns" / "turn_0000" / "cycle"
    comp_dir.mkdir(parents=True, exist_ok=True)
    (comp_dir / "slow_queue_composition.json").write_text(
        json.dumps({"cap": 7, "selected": [], "candidates_seen": 2, "twin_rejected_rows": [],
                    "measured_rejected_rows": [], "weight_gate": {"max_check_weight": 6, "rejected": []}}),
        encoding="utf-8",
    )
    captured: dict = {}

    def fake_cycle(*args, **kwargs):
        captured.update(kwargs)
        return SimpleNamespace(status="ok", artifact_paths={})

    monkeypatch.setattr(campaign, "run_agentic_cycle", fake_cycle)
    monkeypatch.setattr(graph, "_audit_turn_execution", lambda *args, **kwargs: None)
    verification = (
        VerificationConfig(task="cnot_dense", structural=fig3_cnot_structural_config(), promote_top=7)
        if task == "cnot_dense" else VerificationConfig()
    )
    monkeypatch.setattr(graph, "_verification_from_protocol", lambda *args, **kwargs: verification)
    protocol = {"proposal_count": 1, "generations_per_turn": 1, "feedback_mode": ABLATION_FEEDBACK_MODE[ablation],
                "racing": RacingConfig().to_dict(), "slow_workers": 127, "shot_shards": 16, "strict_turns": False}
    if ablation != "full":
        protocol["ablation"] = ablation
    elites = [{"code_hash": f"{i:02x}" * 12, "program_id": f"e{i}", "family": "bb", "n": 72, "n_total": 144,
               "k": 2 + i, "d_search": 6, "max_check_weight": 6, "spec": {"family": "bb"},
               "construct_source": "def construct(rng):\n    return {}", "pareto_rank": 0}
              for i in range(8)]
    hof = [{"code_hash": "aa" * 12, "program_id": "g0003_p0002", "family": "bb", "n": 72, "k": 2, "d_search": 7,
            "max_check_weight": 4, "per_logical_per_round": 1.4e-4, "spec": {"family": "bb"},
            "construct_source": "def construct(rng):\n    return {}"}]
    state = {
        "run_id": "campaign_b144", "run_dir": str(run_dir), "turn": 1,
        "plan": {"provider": "dry_run", "generations": 1, "proposal_count": 1, "rng_seeds_per_program": 1,
                 "family_mix": {"bb": 1.0}, "promotions": [{"code_hash": "bb" * 12}]},
        "protocol": protocol, "spec": {"qubit_budget": 144, "families": ["bb"]},
        "structural_proxy_elites": elites, "hof_summary": hof, "unmeasurable_hashes": [],
        "baseline_summary": {}, "budget": {}, "slow_context_ptr": str(slow_ptr),
    }
    graph.execute_plan_node(state)
    captured["_parent_selection"] = json.loads((run_dir / "turns" / "turn_0001" / "parent_selection.json").read_text())
    return captured


def test_execute_plan_full_keeps_every_channel(monkeypatch, tmp_path: Path) -> None:
    captured = _execute_plan_capture(monkeypatch, tmp_path, ablation="full")
    overlay = captured["prompt_context_overlay"]
    assert captured["ablation"] == "full"
    assert "slow_feedback" in overlay and "measured_identities" in overlay and "last_turn_queue" in overlay
    assert "evidence_tables" in overlay and "strategy_brief" in overlay and overlay["family_quota"] == {"bb": 1}
    assert captured["promotion_priority"] == ["bb" * 12] and captured["promotion_measured"] == {"aa" * 12}
    channels = [row["selection_channels"] for row in overlay["next_parent_specs"]]
    assert ["structural"] in channels
    sel = captured["_parent_selection"]
    # the hall of fame IS consulted under full (the fixture's hof spec cannot be rebuilt,
    # so it yields a protocol error rather than a parent, but the pool is offered)
    assert sel["ablation"] == "full" and sel["structural_quota"] == 6 and sel["runtime_quota"] == 6
    assert sel["runtime_available"] == 1
    assert captured["evidence_rows"]


